#!/usr/bin/env python3
"""Render the desktop app cask for TAG and commit it to the Homebrew tap.

    publish_desktop_cask.py TAG DMG [--print]

GoReleaser OSS cannot build casks from an externally built DMG, so the
release workflow runs this after GoReleaser publishes the DMG. Stable tags
write Casks/ocman-desktop.rb and nightly tags Casks/ocman-desktop-nightly.rb.
--print writes the cask to stdout without publishing.

Environment:
    GITHUB_API_URL      API base (default https://api.github.com)
    HOMEBREW_TAP_REPO   owner/name of the tap (default ocman/homebrew-tap)
    HOMEBREW_TAP_TOKEN  token with Contents read/write access to the tap
"""
import base64
import hashlib
import json
import os
import re
import sys
import urllib.error
import urllib.request

TAG_PATTERN = re.compile(r"^v(\d+\.\d+\.\d+(-nightly\.\d+(?:\.\d+)?)?)$")
DMG_NAME = "ocman-darwin-arm64.dmg"


class PublishError(Exception):
    pass


def cask_name(tag):
    match = TAG_PATTERN.match(tag)
    if not match:
        raise PublishError(f"{tag} is not a nightly or stable release tag")
    return "ocman-desktop-nightly" if match.group(2) else "ocman-desktop"


def render(tag, sha256):
    name = cask_name(tag)
    other = "ocman-desktop" if name.endswith("-nightly") else "ocman-desktop-nightly"
    return f'''# This file was generated by scripts/publish_desktop_cask.py. DO NOT EDIT.
cask "{name}" do
  version "{tag[1:]}"
  sha256 "{sha256}"

  url "https://github.com/ocman/ocman/releases/download/v#{{version}}/{DMG_NAME}"
  name "ocman"
  desc "Desktop app for coding-agent sessions"
  homepage "https://github.com/ocman/ocman"

  livecheck do
    skip "Auto-generated on release."
  end

  conflicts_with cask: "{other}"
  depends_on arch: :arm64
  depends_on formula: "tmux"
  depends_on :macos

  app "ocman.app"

  postflight_steps do
    run "/usr/bin/xattr", args: ["-dr", "com.apple.quarantine", "{{{{appdir}}}}/ocman.app"]
  end

  zap :not_required

  caveats <<~EOS
    ocman needs at least one agent CLI. Install the ones you use:
      brew install opencode               # OpenCode v2 or later
      brew install --cask claude-code     # Claude Code
      brew install --cask codex           # Codex, also enable it in Settings > Platforms
  EOS
end
'''


def request(method, path, body=None):
    base = os.environ.get("GITHUB_API_URL", "https://api.github.com").rstrip("/")
    token = os.environ.get("HOMEBREW_TAP_TOKEN")
    if not token:
        raise PublishError("HOMEBREW_TAP_TOKEN is not set")
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(base + path, data=data, method=method, headers={
        "Accept": "application/vnd.github+json",
        "Authorization": "Bearer " + token,
        "User-Agent": "ocman-release",
    })
    if data is not None:
        req.add_header("Content-Type", "application/json")
    try:
        with urllib.request.urlopen(req, timeout=30) as response:
            return json.load(response)
    except urllib.error.HTTPError as error:
        if method == "GET" and error.code == 404:
            return None
        raise PublishError(f"{method} {path} returned HTTP {error.code}") from None
    except (urllib.error.URLError, TimeoutError, ValueError) as error:
        raise PublishError(f"{method} {path} failed: {error}") from None


def publish(tag, cask):
    repo = os.environ.get("HOMEBREW_TAP_REPO", "ocman/homebrew-tap")
    path = f"/repos/{repo}/contents/Casks/{cask_name(tag)}.rb"
    current = request("GET", path + "?ref=main")
    if current and base64.b64decode(current.get("content", "")).decode() == cask:
        print(f"{cask_name(tag)} is already at {tag}")
        return
    body = {
        "message": f"chore(homebrew): update {cask_name(tag)} to {tag}",
        "content": base64.b64encode(cask.encode()).decode(),
        "branch": "main",
    }
    if current:
        body["sha"] = current["sha"]
    request("PUT", path, body)
    print(f"Updated {cask_name(tag)} to {tag}")


def main(argv):
    args = [arg for arg in argv[1:] if arg != "--print"]
    if len(args) != 2:
        print("usage: publish_desktop_cask.py TAG DMG [--print]", file=sys.stderr)
        return 2
    tag, dmg = args
    try:
        with open(dmg, "rb") as file:
            sha256 = hashlib.sha256(file.read()).hexdigest()
        cask = render(tag, sha256)
        if "--print" in argv:
            sys.stdout.write(cask)
        else:
            publish(tag, cask)
    except (OSError, PublishError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
