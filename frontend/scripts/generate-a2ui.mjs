import { readFile, writeFile } from 'node:fs/promises';
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';

// Compile at build time: production CSP deliberately disallows unsafe-eval.
const base = new URL('../../internal/agentui/', import.meta.url);
const docs = await Promise.all(['common_types.json', 'catalog.json', 'result.schema.json']
  .map(async name => JSON.parse(await readFile(new URL(name, base), 'utf8'))));
const ajv = new Ajv({ strict: false, schemas: docs.slice(0, 2), code: { source: true, esm: true, lines: true } });
const validate = ajv.compile(docs[2]);
let code = standaloneCode(ajv, validate);
// Ajv's standalone ESM exports still use require for runtime helpers.
// Convert only its explicit helper declarations to bundler-compatible imports.
code = code.replace(/const (\w+) = require\("(ajv\/dist\/runtime\/\w+)"\)\.default;/g,
  'import $1Runtime from "$2.js";\nconst $1 = $1Runtime.default ?? $1Runtime;');
if (code.includes('require(')) throw new Error('Unexpected CommonJS dependency in generated A2UI validator');
const output = '// Generated by pnpm generate:a2ui. Do not edit.\n' + code;
const target = new URL('../src/lib/a2uiValidator.generated.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) {
    throw new Error('A2UI schemas changed. Run pnpm generate:a2ui.');
  }
} else {
  await writeFile(target, output);
}
